  const embeddedMessages = new Map([
    ['@{0}: {1} Kuyruk durduruldu.', 1],
    ['{0} Kuyruk durduruldu.', 0],
    ['{0} Önceki kayıt korundu.', 0],
    ['{0} Sıradaki profil bekleniyor.', 0],
    ['{0} Grup molası.', 0]
  ]);
  const escape = literal => literal.replace(/[.*+?^{}$()|[\]\\]/g, '\\$&');
  const templates = [...english].filter(([source]) => /\{\d+\}/.test(source)).map(([source, target]) => {
    const captures = [];
    const pattern = source.split(/(\{\d+\})/).map(part => {
      const slot = /^\{(\d+)\}$/.exec(part);
      if (!slot) return escape(part);
      captures.push(Number(slot[1]));
      return '(.+?)';
    }).join('');
    return {pattern: new RegExp('^' + pattern + '$'), captures, target, embedded: embeddedMessages.get(source),
      specificity: source.replace(/\{\d+\}/g, '').length};
  }).sort((first, second) => second.specificity - first.specificity);

  const pageLocale = (() => {
    const language = document.documentElement.lang || navigator.language;
    try {
      return Intl.getCanonicalLocales(language.replaceAll('_', '-'))[0] || 'en';
    } catch {
      return 'en';
    }
  })();
  const turkish = /^tr(?:-|$)/i.test(pageLocale);

  function text(value) {
    if (typeof value !== 'string' || !value || turkish) return value;
    if (english.has(value)) return english.get(value);
    // Operation history stores messages from older versions as plain Turkish text.
    // Match only the known message formats, leaving names and filenames intact.
    for (const {pattern, captures, target, embedded} of templates) {
      const match = pattern.exec(value);
      if (match) return target.replace(/\{(\d+)\}/g, (_, index) => {
        const slot = Number(index);
        const value = match[captures.indexOf(slot) + 1];
        return slot === embedded ? text(value) : value;
      });
    }
    return value;
  }

  function markup(root) {
    root.host.lang = turkish ? 'tr' : 'en';
    if (turkish) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (node.parentElement?.closest('style, script')) continue;
      const original = node.data.trim();
      if (english.has(original)) node.data = node.data.replace(original, english.get(original));
    }
    for (const element of root.querySelectorAll('[aria-label], [placeholder], [title]')) {
      for (const attribute of ['aria-label', 'placeholder', 'title']) {
        const original = element.getAttribute(attribute);
        if (english.has(original)) element.setAttribute(attribute, english.get(original));
      }
    }
  }

  return {locale: () => pageLocale, text, markup};
